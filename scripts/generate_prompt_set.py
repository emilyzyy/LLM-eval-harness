#!/usr/bin/env python3
"""Generate a deterministic synthetic prompt set for the fake provider.

The fake provider's response to a case contains the case id and, for JSON
cases, a JSON object with a "case_id" field. Expected facts and schemas are
chosen against that so scores are not uniformly 1.0:

- factual cases expect the case id                      -> 1.0
- every 5th factual case also expects an absent fact    -> 0.5
- tool_use cases require "case_id" in the JSON          -> 1.0
- every 4th tool_use case also requires an absent field -> 0.0

Usage:
    python scripts/generate_prompt_set.py --cases 300 \\
        --output evals/prompt_sets/generated_300.yaml

    # Include cases the fake provider rejects with HTTP 400:
    python scripts/generate_prompt_set.py --cases 25 --permanent-failures 2 \\
        --output /tmp/with_failures.yaml
"""
import argparse
from pathlib import Path

import yaml

PERMANENT_ERROR_MARKER = "[[fake:permanent-error]]"

_TOPICS = [
    "thread pitch for fastener",
    "tensile strength of material",
    "tolerance fit class for assembly",
    "surface finish for component",
    "wall thickness for bracket",
    "bend radius for sheet part",
]


def generate(cases: int, permanent_failures: int = 0) -> dict:
    if permanent_failures > cases:
        raise ValueError("permanent_failures cannot exceed cases")
    failing = set()
    if permanent_failures:
        step = cases / permanent_failures
        failing = {int(i * step + step / 2) for i in range(permanent_failures)}

    prompts = []
    factual_seen = 0
    tool_seen = 0
    for i in range(cases):
        case_id = f"gen_{i:04d}"
        topic = _TOPICS[i % len(_TOPICS)]
        text = f"Case {case_id}: state the recommended {topic} P-{i:04d}."
        if i in failing:
            text += f" {PERMANENT_ERROR_MARKER}"

        if i % 3 == 2:
            tool_seen += 1
            required = ["case_id"]
            properties = {"case_id": {"type": "string"}}
            if tool_seen % 4 == 0:
                required.append("unsupported_field")
                properties["unsupported_field"] = {"type": "string"}
            prompts.append({
                "id": case_id,
                "prompt": text + " Return the result as JSON.",
                "expected_tool_calls": [{
                    "schema": {"type": "object", "properties": properties, "required": required},
                }],
                "category": "tool_use",
            })
        else:
            factual_seen += 1
            facts = [case_id]
            if factual_seen % 5 == 0:
                facts.append("unobtainium")
            prompts.append({
                "id": case_id,
                "prompt": text,
                "expected_facts": facts,
                "category": "factual",
            })

    return {
        "name": f"generated_{cases}",
        "version": "1.0",
        "description": "Synthetic prompt set for the fake provider. "
                       "Generated by scripts/generate_prompt_set.py; do not edit by hand.",
        "prompts": prompts,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cases", type=int, default=300)
    parser.add_argument("--permanent-failures", type=int, default=0,
                        help="Number of cases the fake provider will reject with HTTP 400.")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    data = generate(args.cases, args.permanent_failures)
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(yaml.safe_dump(data, sort_keys=False, width=120), encoding="utf-8")
    print(f"Wrote {len(data['prompts'])} cases to {args.output}")


if __name__ == "__main__":
    main()
